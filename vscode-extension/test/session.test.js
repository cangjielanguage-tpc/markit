'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { discover } = require('../src/projects');
const { PreviewSession } = require('../src/session');

test('native preview renders only the current document, preserves source, and switches languages and files', { skip: !process.env.MARKIT_TEST_BINARY, timeout: 90000 }, async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'markit-native-test-'));
  let session;
  t.after(async () => { await session?.dispose(); await fs.rm(root, { recursive: true, force: true, maxRetries: 3 }); });
  await fs.mkdir(path.join(root, 'build/website'), { recursive: true });
  await fs.mkdir(path.join(root, 'docs'));
  await fs.writeFile(path.join(root, 'build/website/markit.json'), JSON.stringify({ title: 'Preview test', format: 'website', theme: 'arctic', i18n: { default: 'zh', target: 'zh', summary: { zh: ['Home', 'Docs'], en: ['Home', 'Docs'] } }, summary: [{ home: true, label: 'Home' }, { file: 'markit.md', label: 'Docs', showDrafts: false }] }));
  const summary = path.join(root, 'build/website/markit.md');
  await fs.writeFile(summary, '- [章节:en{Chapter}:](../../docs/chapter.md)\n- [第二章:en{Second}:](../../docs/second.md)\n');
  const chapter = path.join(root, 'docs/chapter.md'), second = path.join(root, 'docs/second.md');
  const original = '# 标题:en{Title}:\n\n初始正文\n\n[第二章:en{Second}:](*second*#~)\n\n:::en\nInitial prose\n:::\n';
  await fs.writeFile(chapter, original);
  await fs.writeFile(second, '# 第二章:en{Second}:\n\n:::en\nSECOND_DOC\n:::\n');
  const project = (await discover(root))[0], logs = [], frames = [];
  session = new PreviewSession(project, { executable: process.env.MARKIT_TEST_BINARY, startupTimeoutMs: 30000, onPreview: (page, frame) => { frames.push(frame); assert.equal(page.file, session.file); } });
  session.on('log', text => logs.push(text)); session.on('failure', failure => t.diagnostic(failure.message));
  const started = performance.now();
  await session.start('zh', [], chapter);
  assert.match(session.current.body, /初始正文/);
  assert.doesNotMatch(session.current.body, /class="(?:sidebar|top-nav|article-extra|chapter-navigation)"/);
  assert.match(session.current.body, /data-source-start-byte=/);
  await assert.rejects(fs.access(path.join(session.output, 'zh/docs/second.html')), { code: 'ENOENT' });
  assert.equal(await fs.readFile(session.mirror(second), 'utf8'), await fs.readFile(second, 'utf8'), 'other pages supply heading/link context without being rendered');
  assert.doesNotMatch(session.current.body, /class="link-error"/);
  assert.match(session.current.body, /href="[^"]*second\.html#/);
  const assetsCreated = (await fs.stat(path.join(session.output, 'assets'))).birthtimeMs;
  const edited = performance.now(), initialFrames = frames.length;
  await session.update(chapter, original.replace('初始正文', '未保存内容 UNSAVED_MARKER'));
  t.diagnostic(`Initial single-document build: ${Math.round(edited - started)}ms; edit to rendered HTML: ${Math.round(performance.now() - edited)}ms`);
  assert.match(session.current.body, /<p\b[^>]*>[^<]*UNSAVED_MARKER/);
  assert.equal(session.current.background, true);
  assert.equal(frames.length, initialFrames, 'native edit frames are acknowledged privately, never clear the current preview');
  assert.equal(await fs.readFile(chapter, 'utf8'), original);
  assert.equal((await fs.stat(path.join(session.output, 'assets'))).birthtimeMs, assetsCreated, 'incremental page updates preserve shared assets');
  const inFlight = session.update(chapter, original + '\nFIRST_EDIT\n');
  await new Promise(resolve => setTimeout(resolve, 30));
  const newer = session.update(chapter, original + '\nSECOND_EDIT\n');
  const latest = session.update(chapter, original + '\nLATEST_EDIT\n');
  await Promise.all([inFlight, newer, latest]);
  assert.match(session.current.body, /LATEST_EDIT/);
  assert.doesNotMatch(session.current.body, /FIRST_EDIT|SECOND_EDIT/);
  assert.equal(session.child, undefined, 'render finishes without a background watcher or server');
  await session.switchLanguage('en');
  assert.match(session.current.body, /<p\b[^>]*>Initial prose<\/p>/);
  assert.doesNotMatch(session.current.body, /<p\b[^>]*>[^<]*UNSAVED_MARKER/);
  await assert.rejects(fs.access(path.join(session.output, 'en/docs/second.html')), { code: 'ENOENT' });
  await session.selectDocument(second);
  assert.equal(session.current.file, second); assert.match(session.current.body, /SECOND_DOC/);
  await assert.rejects(fs.access(path.join(session.output, 'en/docs/chapter.html')), { code: 'ENOENT' });
  assert(frames.some(frame => frame.shell), 'native rendering must publish a preview shell before final output');
  assert(frames.some(frame => frame.operations.length), 'native rendering must publish meaningful progressive content');
  // Smart-link href and mirrored context assertions above validate heading context.
  // Preview transport suppresses terminal progress bars, so do not assert their log wording.
  await session.dispose(); await session.dispose();
});
